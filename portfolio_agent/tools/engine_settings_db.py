"""
Engine settings — single-row, database-backed store for the market-only
weighting engine's parameters: source weights per horizon, the
deterministic conviction guardrail thresholds, and APEX model selection
(champion, ordered fallbacks, optional challenger).

These numbers used to be Python module constants (portfolio_agent.tools.
weight_engine.BASE / HORIZON_BASE_WEIGHTS / DEFAULT_BASE_WEIGHTS / WEIGHT_FLOOR,
and the two thresholds inline in pipeline.daily.apex._apply_conviction_guardrails).
They still exist there as the SEED DEFAULTS (and as the fixed inputs Phase 1's
golden tests check), but the values weight_engine and apex actually use at
runtime now come from this table, so an administrator can tune them without a
code change or deploy. Nothing here is user-scoped: this is global, admin-only
configuration for the shared, market-only generation path.

instrument_type_horizons_json decides which prediction horizons the pipeline generates for each instrument type
(see SEED_INSTRUMENT_TYPE_HORIZONS): stocks and ETFs get all four, mutual funds / target-date funds only the long
ones (their NAV posts once a day and 401(k) frequent-trading rules make a 5-day call unactionable), cash-like
instruments none. The pipeline intersects this with the day's scheduled horizons.

The APEX model columns are seeded from apex_dual_run.DEFAULT_CHAMPION /
DEFAULT_FALLBACKS (column DEFAULTs, so an existing row picks them up when the
columns are added) and hold model DISPLAY LABELS ("Claude-Sonnet"), resolved
against apex_dual_run.APEX_MODELS at run time.

Table: engine_settings — exactly one row (id = 1, enforced by CHECK).
"""

from __future__ import annotations

import json
import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone

from portfolio_agent.tools import bucket_edges as be
from portfolio_agent.tools import trade_plan as _tp
from portfolio_agent.tools.db import db_conn, migrate_columns

_SOURCES = ("news", "research", "macro", "fundamentals", "valuation")

_ALL_HORIZONS = [5, 21, 63, 250]
_LONG_HORIZONS = [63, 250]
# Seed defaults: {instrument_type: [horizon_days]} — an empty list means "never predicted".
SEED_INSTRUMENT_TYPE_HORIZONS: dict[str, list[int]] = {
    "STOCK": _ALL_HORIZONS, "ETF": _ALL_HORIZONS, "ETN": _ALL_HORIZONS, "BOND": _ALL_HORIZONS,
    "OTHER": _ALL_HORIZONS, "UNKNOWN": _ALL_HORIZONS,
    "MUTUAL_FUND": _LONG_HORIZONS, "TARGET_DATE_FUND": _LONG_HORIZONS,
    "CIT": [], "STABLE_VALUE": [], "CASH": [], "MONEY_MARKET": [],
}
# Cadence: how often each horizon is generated by the scheduled (morning) batch. Event triggers and the legacy force-all path are
# separate. Seed defaults = what the code scheduled before this became a setting; "never" turns a horizon's routine run off.
CADENCE_RULES = ("weekly_monday", "monthly_first_trading_day", "quarterly_first_trading_day", "never")
CADENCE_LABELS = {
    "weekly_monday": "every Monday",
    "monthly_first_trading_day": "first trading day of each month",
    "quarterly_first_trading_day": "first trading day of each quarter",
    "never": "never (not scheduled)",
}
SEED_HORIZON_CADENCE: dict[int, str] = {5: "weekly_monday", 21: "weekly_monday", 63: "monthly_first_trading_day",
                                        250: "quarterly_first_trading_day"}
SIM_GUARDRAIL_MODES = ("shadow", "cap")
SEED_SIM_SETTINGS: dict = {
    "sim_paths": 10000, "sim_lookback_days": 500, "sim_block_len": 5,
    "sim_flag_min_conviction": 7.0, "sim_flag_max_p_target": 0.35,
    "sim_guardrail_mode": "shadow",       # shadow = flag only | cap = also cap conviction and composite to 5
    "blend_min_n": 150,                   # matured rows a horizon needs before a blended probability is fitted
}
_UNSET = object()   # distinguishes "leave apex_challenger_model alone" from "clear it (None)"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


_schema_ready: set[str] = set()


@contextmanager
def _db():
    """A connection to the engine-settings table. Create + migrate + seed run once per process per DB file, not on
    every connection (parallel pipeline threads each open one; per-connection DDL fought for the write lock)."""
    from portfolio_agent.tools import db as _db_module
    key = str(_db_module.DB_PATH)

    def _setup(conn: sqlite3.Connection) -> None:
        _create_schema(conn)
        _migrate(conn)
        _seed(conn)
        conn.commit()
        _schema_ready.add(key)
    with db_conn(setup=None if key in _schema_ready else _setup) as conn:
        yield conn


def _create_schema(conn: sqlite3.Connection) -> None:
    conn.execute("""
        CREATE TABLE IF NOT EXISTS engine_settings (
            id                          INTEGER PRIMARY KEY CHECK (id = 1),
            base_weights                TEXT NOT NULL,
            horizon_base_weights        TEXT NOT NULL,
            default_base_weights        TEXT NOT NULL,
            weight_floor                REAL NOT NULL,
            no_news_conviction_threshold REAL NOT NULL,
            no_news_cap                 REAL NOT NULL,
            bounce_return_threshold     REAL NOT NULL,
            bounce_cap                  REAL NOT NULL,
            version                     INTEGER NOT NULL DEFAULT 1,
            created_at                  TEXT NOT NULL,
            updated_at                  TEXT NOT NULL,
            updated_by                  TEXT
        )
    """)


def _migrate(conn: sqlite3.Connection) -> None:
    """Idempotent column additions. Fresh installs get them the same way (the
    CREATE above is the original shape), so there is exactly one definition."""
    from portfolio_agent.tools.apex_dual_run import (
        DEFAULT_CHAMPION, DEFAULT_FALLBACKS, DEFAULT_RANDOM_POOL, DEFAULT_SELECTION_MODE,
    )

    def _lit(s: str) -> str:
        return "'" + s.replace("'", "''") + "'"

    migrate_columns(conn, "engine_settings", [
        ("apex_champion_model",        f"TEXT NOT NULL DEFAULT {_lit(DEFAULT_CHAMPION)}"),
        ("apex_fallback_models",       f"TEXT NOT NULL DEFAULT {_lit(json.dumps(list(DEFAULT_FALLBACKS)))}"),
        ("apex_challenger_model",      "TEXT"),                         # NULL = challenger off
        ("apex_challenger_sample_pct", "REAL NOT NULL DEFAULT 0"),      # 0–100, % of tickers
        # "champion" (one fixed model) or "random_pool" (each ticker draws one model from apex_random_pool, per ticker per day)
        ("apex_selection_mode",        f"TEXT NOT NULL DEFAULT {_lit(DEFAULT_SELECTION_MODE)}"),
        ("apex_random_pool",           f"TEXT NOT NULL DEFAULT {_lit(json.dumps(list(DEFAULT_RANDOM_POOL)))}"),
        ("instrument_type_horizons_json", f"TEXT NOT NULL DEFAULT {_lit(json.dumps(SEED_INSTRUMENT_TYPE_HORIZONS))}"),
        # Horizon-scaled return buckets (see tools.bucket_edges): the current edges and their version. An existing row takes
        # the seed (version 2); version 1 is the old fixed ±1% / ±5% / 2% for every horizon and lives only in the history.
        ("horizon_bucket_edges_json",     f"TEXT NOT NULL DEFAULT {_lit(be.table_to_json(be.SEED_EDGES))}"),
        ("bucket_edges_version",          f"INTEGER NOT NULL DEFAULT {be.SEED_VERSION}"),
        ("horizon_cadence_json",          f"TEXT NOT NULL DEFAULT {_lit(json.dumps({str(h): r for h, r in SEED_HORIZON_CADENCE.items()}))}"),
        # Deterministic trade plan rules (tools.trade_plan): stop / target multiples, minimum reward:risk, widest stop, loss budget.
        ("trade_plan_json",               f"TEXT NOT NULL DEFAULT {_lit(json.dumps(_plan_to_json(_tp.seed_settings())))}"),
        # Plan simulation (tools.plan_simulator): paths, history pool, block length, the disagreement flag and its guardrail mode.
        ("sim_json",                      f"TEXT NOT NULL DEFAULT {_lit(json.dumps(SEED_SIM_SETTINGS))}"),
    ])
    conn.execute("""
        CREATE TABLE IF NOT EXISTS bucket_edges_history (
            version     INTEGER PRIMARY KEY,
            edges_json  TEXT NOT NULL,
            created_at  TEXT NOT NULL,
            created_by  TEXT
        )""")


def _seed(conn: sqlite3.Connection) -> None:
    """Insert the singleton row from weight_engine's own module constants —
    the seed defaults — if it doesn't exist yet. Never overwrites an existing row.
    The APEX model columns take their column DEFAULTs (see _migrate)."""
    from portfolio_agent.tools.weight_engine import BASE, DEFAULT_BASE_WEIGHTS, HORIZON_BASE_WEIGHTS, WEIGHT_FLOOR
    now = _now()
    conn.execute(
        """INSERT OR IGNORE INTO engine_settings
               (id, base_weights, horizon_base_weights, default_base_weights, weight_floor,
                no_news_conviction_threshold, no_news_cap, bounce_return_threshold, bounce_cap,
                created_at, updated_at)
           VALUES (1, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        [json.dumps(BASE), json.dumps({str(k): v for k, v in HORIZON_BASE_WEIGHTS.items()}),
         json.dumps(DEFAULT_BASE_WEIGHTS), WEIGHT_FLOOR,
         7.0, 5.0, -0.05, 5.0, now, now],
    )
    _seed_edges_history(conn)


def _seed_edges_history(conn: sqlite3.Connection) -> None:
    """Version 1 (the legacy fixed edges, every horizon) and whatever version the settings row currently holds, so the scorer
    can rebuild the edges of ANY prediction. Append-only: INSERT OR IGNORE, never an update."""
    now = _now()
    conn.execute("INSERT OR IGNORE INTO bucket_edges_history (version, edges_json, created_at, created_by) VALUES (?, ?, ?, 'system')",
                 [be.LEGACY_VERSION, be.table_to_json(be.LEGACY_TABLE), now])
    conn.execute("INSERT OR IGNORE INTO bucket_edges_history (version, edges_json, created_at, created_by) "
                 "SELECT bucket_edges_version, horizon_bucket_edges_json, ?, 'system' FROM engine_settings WHERE id = 1", [now])


def _row_to_dict(row: sqlite3.Row) -> dict:
    d = dict(row)
    d["base_weights"] = json.loads(d["base_weights"])
    d["horizon_base_weights"] = {int(k): v for k, v in json.loads(d["horizon_base_weights"]).items()}
    d["default_base_weights"] = json.loads(d["default_base_weights"])
    try:
        d["apex_fallback_models"] = list(json.loads(d.get("apex_fallback_models") or "[]"))
    except (TypeError, ValueError):
        d["apex_fallback_models"] = []      # apex_dual_run.build_model_plan falls back to the code defaults
    try:
        d["apex_random_pool"] = list(json.loads(d.get("apex_random_pool") or "[]"))
    except (TypeError, ValueError):
        d["apex_random_pool"] = []          # build_model_plan falls back to the default pool
    try:
        stored = json.loads(d.get("instrument_type_horizons_json") or "{}")
    except (TypeError, ValueError):
        stored = {}
    # A type missing from the stored map (e.g. one added after it was saved) takes its seed default, never a guess.
    d["instrument_type_horizons"] = {t: list(stored.get(t, h)) for t, h in SEED_INSTRUMENT_TYPE_HORIZONS.items()}
    try:
        stored_c = json.loads(d.get("horizon_cadence_json") or "{}")
    except (TypeError, ValueError):
        stored_c = {}
    d.update(_plan_from_json(d.get("trade_plan_json")))
    d.update(_sim_from_json(d.get("sim_json")))
    # a horizon (or an unknown rule) missing from the stored map takes the seed, never a guess
    d["horizon_cadence"] = {h: (stored_c.get(str(h)) if stored_c.get(str(h)) in CADENCE_RULES else r)
                            for h, r in SEED_HORIZON_CADENCE.items()}
    try:
        d["horizon_bucket_edges"] = be.table_from_json(d.get("horizon_bucket_edges_json") or "{}")
    except (TypeError, ValueError, KeyError):
        d["horizon_bucket_edges"] = dict(be.SEED_EDGES)
    return d


_PLAN_HORIZON_KEYS = ("plan_stop_atr_mult", "plan_target_r_multiple", "plan_max_stop_pct")
_PLAN_PROFILES = ("conservative", "moderate", "aggressive")


def _plan_to_json(settings: dict) -> dict:
    return {k: ({str(h): v for h, v in val.items()} if k in _PLAN_HORIZON_KEYS else val) for k, val in settings.items()}


def _plan_from_json(raw) -> dict:
    """The five plan_* settings from their stored JSON; anything missing or unreadable takes the seed, never a guess."""
    seed = _tp.seed_settings()
    try:
        stored = json.loads(raw or "{}")
    except (TypeError, ValueError):
        stored = {}
    out: dict = {}
    for k in _PLAN_HORIZON_KEYS:
        got = stored.get(k) or {}
        out[k] = {h: float(got.get(str(h), v)) for h, v in seed[k].items()}
    got = stored.get("plan_max_loss_pct_by_risk_profile") or {}
    out["plan_max_loss_pct_by_risk_profile"] = {p: float(got.get(p, v)) for p, v in seed["plan_max_loss_pct_by_risk_profile"].items()}
    try:
        out["plan_min_reward_risk"] = float(stored.get("plan_min_reward_risk", seed["plan_min_reward_risk"]))
    except (TypeError, ValueError):
        out["plan_min_reward_risk"] = seed["plan_min_reward_risk"]
    return out


def _validate_trade_plan(patch: dict, current: dict) -> dict:
    """Merge a (partial) plan_* patch onto the current settings and validate the result. Returns the full merged dict."""
    unknown = set(patch) - set(current)
    if unknown:
        raise ValueError(f"trade_plan: unknown setting(s) {sorted(unknown)}")
    merged = {k: (dict(v) if isinstance(v, dict) else v) for k, v in current.items()}
    for k, v in patch.items():
        if isinstance(merged[k], dict):
            if not isinstance(v, dict):
                raise ValueError(f"{k}: expected a mapping")
            keys = _PLAN_PROFILES if k == "plan_max_loss_pct_by_risk_profile" else _tp.SUPPORTED_HORIZONS
            for kk, vv in v.items():
                kk = str(kk).lower() if k == "plan_max_loss_pct_by_risk_profile" else int(kk)
                if kk not in keys:
                    raise ValueError(f"{k}: unsupported key {kk!r}; supported: {list(keys)}")
                merged[k][kk] = float(vv)
        else:
            merged[k] = float(v)
    for k in ("plan_stop_atr_mult", "plan_target_r_multiple"):
        if any(not (0 < x <= 20) for x in merged[k].values()):
            raise ValueError(f"{k}: every multiple must be > 0 and at most 20")
    if any(not (0 < x <= 1) for x in merged["plan_max_stop_pct"].values()):
        raise ValueError("plan_max_stop_pct: every value must be a fraction above 0 and at most 1 (0.08 = 8%)")
    if any(not (0 < x <= 0.1) for x in merged["plan_max_loss_pct_by_risk_profile"].values()):
        raise ValueError("plan_max_loss_pct_by_risk_profile: every value must be a fraction above 0 and at most 0.1 (10% of the portfolio)")
    if not (0 < merged["plan_min_reward_risk"] <= 20):
        raise ValueError("plan_min_reward_risk: must be > 0 and at most 20")
    return merged


def _sim_from_json(raw) -> dict:
    """The sim_* settings from their stored JSON; anything missing or unreadable takes the seed, never a guess."""
    try:
        stored = json.loads(raw or "{}")
    except (TypeError, ValueError):
        stored = {}
    out: dict = {}
    for k, seed in SEED_SIM_SETTINGS.items():
        v = stored.get(k, seed)
        try:
            out[k] = (v if v in SIM_GUARDRAIL_MODES else seed) if k == "sim_guardrail_mode" else \
                     (int(v) if isinstance(seed, int) else float(v))
        except (TypeError, ValueError):
            out[k] = seed
    return out


def _validate_sim(patch: dict, current: dict) -> dict:
    """Merge a (partial) sim_* patch onto the current settings and validate the result. Returns the full merged dict."""
    unknown = set(patch) - set(SEED_SIM_SETTINGS)
    if unknown:
        raise ValueError(f"sim: unknown setting(s) {sorted(unknown)}")
    merged = dict(current)
    for k, v in patch.items():
        if k == "sim_guardrail_mode":
            if v not in SIM_GUARDRAIL_MODES:
                raise ValueError(f"sim_guardrail_mode: must be one of {list(SIM_GUARDRAIL_MODES)}, got {v!r}")
            merged[k] = v
        elif isinstance(SEED_SIM_SETTINGS[k], int):
            if isinstance(v, bool) or int(v) != float(v):
                raise ValueError(f"{k}: must be a whole number, got {v!r}")
            merged[k] = int(v)
        else:
            merged[k] = float(v)
    from portfolio_agent.tools import plan_simulator as _ps
    if not (100 <= merged["sim_paths"] <= 100_000):
        raise ValueError("sim_paths: must be between 100 and 100000")
    if not (_ps.MIN_HISTORY_BARS <= merged["sim_lookback_days"] <= 2500):
        raise ValueError(f"sim_lookback_days: must be between {_ps.MIN_HISTORY_BARS} and 2500")
    if not (1 <= merged["sim_block_len"] <= 30):
        raise ValueError("sim_block_len: must be between 1 and 30")
    if not (0 <= merged["sim_flag_min_conviction"] <= 10):
        raise ValueError("sim_flag_min_conviction: must be between 0 and 10")
    if not (0 < merged["sim_flag_max_p_target"] <= 1):
        raise ValueError("sim_flag_max_p_target: must be above 0 and at most 1")
    if not (30 <= merged["blend_min_n"] <= 100_000):
        raise ValueError("blend_min_n: must be between 30 and 100000")
    return merged


def get_sim_settings(settings: dict | None = None) -> dict:
    """Just the sim_* settings."""
    s = settings or get_engine_settings()
    return {k: s[k] for k in SEED_SIM_SETTINGS}


def get_trade_plan_settings(settings: dict | None = None) -> dict:
    """Just the plan_* settings, in the shape tools.trade_plan reads."""
    s = settings or get_engine_settings()
    return {k: s[k] for k in _tp.seed_settings()}


def get_edges_history(version: int) -> dict[int, "be.Edges"] | None:
    """The edges table that was current as `version` (None if there never was such a version). Immutable once written."""
    with _db() as c:
        row = c.execute("SELECT edges_json FROM bucket_edges_history WHERE version = ?", [int(version)]).fetchone()
    return be.table_from_json(row["edges_json"]) if row else None


def current_bucket_edges(*, conn: sqlite3.Connection | None = None) -> tuple[int, dict[int, "be.Edges"]]:
    """(version, {horizon: Edges}) in force NOW — what a prediction made today is prompted with and stored under."""
    s = get_engine_settings(conn=conn)
    return int(s["bucket_edges_version"]), s["horizon_bucket_edges"]


def _validate_cadence(cadence: dict) -> dict[int, str]:
    """{horizon_days: rule}: supported horizons only, rule one of CADENCE_RULES."""
    if not isinstance(cadence, dict) or not cadence:
        raise ValueError("horizon_cadence: expected {horizon_days: rule}")
    clean: dict[int, str] = {}
    for h, rule in cadence.items():
        try:
            hh = int(h)
        except (TypeError, ValueError):
            raise ValueError(f"horizon_cadence: {h!r} is not a horizon")
        if hh not in SEED_HORIZON_CADENCE:
            raise ValueError(f"horizon_cadence: unsupported horizon {hh}; supported: {sorted(SEED_HORIZON_CADENCE)}")
        if rule not in CADENCE_RULES:
            raise ValueError(f"horizon_cadence[{hh}]: unknown rule {rule!r}; allowed: {list(CADENCE_RULES)}")
        clean[hh] = rule
    return clean


def scheduled_cadence(settings: dict | None = None) -> dict[str, str]:
    """The cadence in the shape events.scheduler reads: {"horizon_5d": rule, ...}."""
    settings = settings or get_engine_settings()
    return {f"horizon_{h}d": r for h, r in sorted(settings["horizon_cadence"].items())}


def get_engine_settings(*, conn: sqlite3.Connection | None = None) -> dict:
    """The current effective settings (seeded from weight_engine's defaults on first use). Pass *conn* to read inside
    the caller's own transaction (it then sees that transaction's uncommitted changes)."""
    if conn is not None:
        return _row_to_dict(conn.execute("SELECT * FROM engine_settings WHERE id = 1").fetchone())
    with _db() as c:
        row = c.execute("SELECT * FROM engine_settings WHERE id = 1").fetchone()
    return _row_to_dict(row)


def _normalize_weights(weights: dict, *, what: str) -> dict:
    missing = set(_SOURCES) - set(weights)
    extra = set(weights) - set(_SOURCES)
    if missing or extra:
        raise ValueError(f"{what}: expected exactly the sources {sorted(_SOURCES)}, "
                         f"got {sorted(weights)} (missing {sorted(missing)}, unexpected {sorted(extra)})")
    values = [float(v) for v in weights.values()]
    if any(v < 0 for v in values):
        raise ValueError(f"{what}: weights cannot be negative")
    total = sum(values)
    if total <= 0:
        raise ValueError(f"{what}: weights must sum to a positive number")
    return {k: round(float(v) / total, 4) for k, v in weights.items()}


def _validate_horizons(horizons: dict) -> dict[str, list[int]]:
    """{instrument_type: [horizon_days]}: known types, supported horizons only, no duplicates; [] = never predicted."""
    from portfolio_agent.domain import INSTRUMENT_TYPES
    from portfolio_agent.tools.weight_engine import SUPPORTED_HORIZONS
    if not isinstance(horizons, dict) or not horizons:
        raise ValueError("instrument_type_horizons: expected {instrument_type: [horizon_days]}")
    clean: dict[str, list[int]] = {}
    for itype, hs in horizons.items():
        if itype not in INSTRUMENT_TYPES:
            raise ValueError(f"instrument_type_horizons: unknown instrument type {itype!r}")
        try:
            vals = [int(h) for h in hs]
        except (TypeError, ValueError):
            raise ValueError(f"instrument_type_horizons[{itype}]: must be a list of horizon days")
        bad = sorted(set(vals) - set(SUPPORTED_HORIZONS))
        if bad:
            raise ValueError(f"instrument_type_horizons[{itype}]: unsupported horizon(s) {bad}; supported: {list(SUPPORTED_HORIZONS)}")
        clean[itype] = sorted(set(vals))
    return clean


def horizons_for_instrument_type(instrument_type: str | None, settings: dict | None = None) -> list[int]:
    """The horizons the pipeline may generate for this instrument type. None / unclassified = the stock path."""
    settings = settings or get_engine_settings()
    table = settings["instrument_type_horizons"]
    return list(table.get(instrument_type or "UNKNOWN", table["UNKNOWN"]))


def _check_model_label(label: str, what: str) -> str:
    from portfolio_agent.tools.apex_dual_run import known_model_labels
    label = (label or "").strip()
    if label not in known_model_labels():
        raise ValueError(f"{what}: unknown APEX model {label!r}; known: {list(known_model_labels())}")
    return label


def update_engine_settings(*, updated_by: str, expected_version: int | None = None,
                           base_weights: dict | None = None,
                           horizon_base_weights: dict[int, dict] | None = None,
                           default_base_weights: dict | None = None,
                           weight_floor: float | None = None,
                           no_news_conviction_threshold: float | None = None,
                           no_news_cap: float | None = None,
                           bounce_return_threshold: float | None = None,
                           bounce_cap: float | None = None,
                           apex_champion_model: str | None = None,
                           apex_fallback_models: list[str] | None = None,
                           apex_challenger_model=_UNSET,
                           apex_challenger_sample_pct: float | None = None,
                           apex_selection_mode: str | None = None,
                           apex_random_pool: list[str] | None = None,
                           instrument_type_horizons: dict | None = None,
                           horizon_bucket_edges: dict | None = None,
                           horizon_cadence: dict | None = None,
                           trade_plan: dict | None = None,
                           sim: dict | None = None,
                           conn: sqlite3.Connection | None = None) -> dict:
    """
    Update one or more settings groups. Every weight dict is validated (exactly
    the five sources, non-negative) and normalized to sum to 1.0 so an admin's
    edit is never silently mis-weighted. APEX model labels must be known to
    apex_dual_run.APEX_MODELS; apex_selection_mode is "champion" (one fixed model) or
    "random_pool" (each ticker draws one model from apex_random_pool, at least 2, per
    ticker per day — see apex_dual_run.plan_for_ticker); apex_challenger_model=None turns the challenger
    off; apex_challenger_sample_pct is a percentage 0–100. Raises ValueError on
    bad input, VersionConflict-style RuntimeError if expected_version is stale.

    horizon_bucket_edges: {horizon: {flat, strong, significant}} (fractions; a partial dict changes only the horizons given).
    Validated (0 < flat < significant < strong). A CHANGE bumps bucket_edges_version and appends the new table to
    bucket_edges_history; predictions already made keep the version they were made under and are never rescored.

    horizon_cadence: {horizon_days: rule} with rule in CADENCE_RULES (a partial dict changes only the horizons given); read by the
    scheduled batch on its next run.

    trade_plan: a (partial) {plan_stop_atr_mult, plan_target_r_multiple, plan_min_reward_risk, plan_max_stop_pct,
    plan_max_loss_pct_by_risk_profile} patch merged onto the current values and validated (see tools.trade_plan). Plans already
    written are immutable and keep the rules_version they were made under; a change applies to NEW plans.

    sim: a (partial) {sim_paths, sim_lookback_days, sim_block_len, sim_flag_min_conviction, sim_flag_max_p_target,
    sim_guardrail_mode} patch, merged and validated (see tools.plan_simulator). Takes effect on the next simulation.

    conn: join the caller's transaction (nothing is committed here, so a settings change and its audit event can land
    together). The caller must have touched the engine-settings table once beforehand (get_engine_settings()) so its
    schema exists — creating it from inside someone else's write transaction would block.
    """
    fields: dict = {}
    if base_weights is not None:
        fields["base_weights"] = json.dumps(_normalize_weights(base_weights, what="base_weights"))
    if default_base_weights is not None:
        fields["default_base_weights"] = json.dumps(_normalize_weights(default_base_weights, what="default_base_weights"))
    if horizon_base_weights is not None:
        normalized = {str(h): _normalize_weights(w, what=f"horizon_base_weights[{h}]")
                     for h, w in horizon_base_weights.items()}
        fields["horizon_base_weights"] = json.dumps(normalized)
    if weight_floor is not None:
        if not (0.0 <= weight_floor <= 0.3):
            raise ValueError(f"weight_floor must be between 0.0 and 0.3, got {weight_floor}")
        fields["weight_floor"] = float(weight_floor)
    if no_news_conviction_threshold is not None:
        fields["no_news_conviction_threshold"] = float(no_news_conviction_threshold)
    if no_news_cap is not None:
        fields["no_news_cap"] = float(no_news_cap)
    if bounce_return_threshold is not None:
        fields["bounce_return_threshold"] = float(bounce_return_threshold)
    if bounce_cap is not None:
        fields["bounce_cap"] = float(bounce_cap)
    if apex_champion_model is not None:
        fields["apex_champion_model"] = _check_model_label(apex_champion_model, "apex_champion_model")
    if apex_fallback_models is not None:
        labels = [_check_model_label(m, "apex_fallback_models") for m in apex_fallback_models]
        fields["apex_fallback_models"] = json.dumps(list(dict.fromkeys(labels)))
    if apex_challenger_model is not _UNSET:
        fields["apex_challenger_model"] = (None if apex_challenger_model in (None, "")
                                           else _check_model_label(apex_challenger_model, "apex_challenger_model"))
    if apex_random_pool is not None:
        pool = list(dict.fromkeys(_check_model_label(m, "apex_random_pool") for m in apex_random_pool))
        if len(pool) < 2:
            raise ValueError(f"apex_random_pool needs at least 2 different models, got {pool}")
        fields["apex_random_pool"] = json.dumps(pool)
    if apex_selection_mode is not None:
        from portfolio_agent.tools.apex_dual_run import SELECTION_MODES
        if apex_selection_mode not in SELECTION_MODES:
            raise ValueError(f"apex_selection_mode must be one of {list(SELECTION_MODES)}, got {apex_selection_mode!r}")
        fields["apex_selection_mode"] = apex_selection_mode
    if apex_challenger_sample_pct is not None:
        if not (0.0 <= float(apex_challenger_sample_pct) <= 100.0):
            raise ValueError(f"apex_challenger_sample_pct must be between 0 and 100, got {apex_challenger_sample_pct}")
        fields["apex_challenger_sample_pct"] = float(apex_challenger_sample_pct)
    if instrument_type_horizons is not None:
        merged = {**get_engine_settings(conn=conn)["instrument_type_horizons"], **_validate_horizons(instrument_type_horizons)}
        fields["instrument_type_horizons_json"] = json.dumps(merged)
    if horizon_cadence is not None:
        merged_c = {**get_engine_settings(conn=conn)["horizon_cadence"], **_validate_cadence(horizon_cadence)}
        fields["horizon_cadence_json"] = json.dumps({str(h): r for h, r in sorted(merged_c.items())})
    if trade_plan is not None:
        merged_p = _validate_trade_plan(trade_plan, get_trade_plan_settings(get_engine_settings(conn=conn)))
        fields["trade_plan_json"] = json.dumps(_plan_to_json(merged_p))
    if sim is not None:
        fields["sim_json"] = json.dumps(_validate_sim(sim, get_sim_settings(get_engine_settings(conn=conn))))
    bump_edges = False
    if horizon_bucket_edges is not None:
        current = get_engine_settings(conn=conn)["horizon_bucket_edges"]
        merged = {h: current[h] for h in current}
        for h, e in horizon_bucket_edges.items():
            merged[int(h)] = be.validate_table({**{hh: ee for hh, ee in current.items()}, int(h): e})[int(h)]
        merged = be.validate_table(merged)
        if merged != current:
            fields["horizon_bucket_edges_json"] = be.table_to_json(merged)
            bump_edges = True
    if not fields:
        return get_engine_settings(conn=conn)

    fields["updated_at"] = _now()
    fields["updated_by"] = updated_by
    cols = list(fields)
    sql = (f"UPDATE engine_settings SET {', '.join(f'{c} = ?' for c in cols)}, "
           + ("bucket_edges_version = bucket_edges_version + 1, " if bump_edges else "") + "version = version + 1 WHERE id = 1")
    params = [fields[c] for c in cols]
    if expected_version is not None:
        sql += " AND version = ?"
        params.append(expected_version)
    def _record_history(cx: sqlite3.Connection) -> None:
        if bump_edges:
            cx.execute("INSERT OR IGNORE INTO bucket_edges_history (version, edges_json, created_at, created_by) "
                       "SELECT bucket_edges_version, horizon_bucket_edges_json, ?, ? FROM engine_settings WHERE id = 1",
                       [_now(), updated_by])

    if conn is not None:
        n = conn.execute(sql, params).rowcount
        if n == 0 and expected_version is not None:
            raise RuntimeError("engine settings changed since you loaded them; reload and retry")
        _record_history(conn)
        return get_engine_settings(conn=conn)
    with _db() as c:
        n = c.execute(sql, params).rowcount
        if n:
            _record_history(c)
        c.commit()          # db_conn() never commits on exit; without this every update was silently rolled back
    if n == 0 and expected_version is not None:
        raise RuntimeError("engine settings changed since you loaded them; reload and retry")
    return get_engine_settings()


